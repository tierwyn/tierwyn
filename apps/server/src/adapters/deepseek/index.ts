type SpawnFn = (cmd: string, args: string[], opts: { cwd?: string }) => ChildProcess;

/** Split a stored model name of form "provider/modelId" into its parts. */
function splitModel(model: string): { provider?: string; modelId: string } {
  const i = model.indexOf('/');
  if (i === -1) return { modelId: model };
  return { provider: model.slice(0, i), modelId: model.slice(i + 1) };
}

/** Tierwyn catalogue uses `z.ai`; dsh's pi-ai plugin registers `zai`. */
const DSH_PROVIDER_ALIASES: Record<string, string> = { 'z.ai': 'zai' };

const SAFE_PROVIDER_RE = /^[a-z0-9][a-z0-9._-]*$/i;

function userPatchConfiguresProvider(dshHome: string, provider: string): boolean {
  const escaped = provider.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const keyRe = new RegExp(`^\\s*['"]?${escaped}['"]?\\s*:`, 'm');
  for (const file of [
    join(dshHome, 'profiles', 'sdk', 'cordis.patch.yml'),
    join(dshHome, 'cordis.patch.yml'),
  ]) {
    if (!existsSync(file)) continue;
    try {
      const text = readFileSync(file, 'utf8');
      if (text.includes('providers:') && keyRe.test(text)) return true;
    } catch { /* ignore unreadable */ }
  }
  return false;
}

/**
 * Ensure a `--patch` overlay exists for non-`deepseek-official` pi-ai providers
 * (e.g. `zai`, `openrouter`, `openai`, `anthropic`, `xai`) unless the operator
 * already configured that provider in their own `cordis.patch.yml`.
 * Stored under `<dshHome>/.tierwyn-patches/` so it is visible inside `bwrap`.
 */
export function ensurePiAiProviderPatch(dshHome: string, provider?: string): string | null {
  if (!provider || provider === 'deepseek-official' || !SAFE_PROVIDER_RE.test(provider)) return null;
  if (userPatchConfiguresProvider(dshHome, provider)) return null;
  const dir = join(dshHome, '.tierwyn-patches');
  const file = join(dir, `pi-ai-${provider}.yml`);
  const content = [
    '# Auto-generated by Tierwyn to enable pi-ai provider with ambient env key discovery.',
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    `      ${provider}: {}`,
    '',
  ].join('\n');
  try {
    mkdirSync(dir, { recursive: true });
    writeFileSync(file, content, { mode: 0o600 });
    return file;
  } catch {
    return null;
  }
}

const DEEPSEEK_REASONING = new Set(['low', 'high', 'max']);
const HELPER_SUMMARY_CAP = 4000;

function extractAssistantSummary(blocks: unknown): string | undefined {
  if (!Array.isArray(blocks)) return undefined;
  const parts: string[] = [];
  for (const b of blocks) {
    if (b && typeof b === 'object' && (b as Record<string, unknown>).type === 'text') {
      const t = (b as Record<string, unknown>).text;
      if (typeof t === 'string' && t) parts.push(t);
    }
  }
  const joined = parts.join('\n').trim();
  if (!joined) return undefined;
  return joined.length > HELPER_SUMMARY_CAP ? joined.slice(0, HELPER_SUMMARY_CAP) : joined;
}

/** Resolve dsh initialize reasoningEffort from per-message options, else the session fallback. */
export function resolveDeepSeekReasoningEffort(
  options?: PromptOptions | null,
  fallback?: string,
): string | undefined {
  const raw = options?.['reasoningEffort'];
  if (typeof raw === 'string' && DEEPSEEK_REASONING.has(raw)) return raw;
  return fallback;
}

/** Map a catalogue `provider/model` string to the ids `dsh initialize` accepts. */
function toDshInit(model: string): { provider?: string; modelId: string } {
  const { provider: rawProvider, modelId: rawModel } = splitModel(model);
  const provider = rawProvider ? (DSH_PROVIDER_ALIASES[rawProvider] ?? rawProvider) : undefined;
  // zai catalogue ids are lowercase (`glm-5.3-flash`); Tierwyn labels are mixed-case.
  const modelId = provider === 'zai' ? rawModel.toLowerCase() : rawModel;
  return { provider, modelId };
}

/** Locate a persisted `.dsh/sessions/<slug>/<sessionId>` directory on disk. */
export function locateDshSessionDir(dshHome: string, nativeSessionId: string): string | null {
  if (!nativeSessionId || nativeSessionId.includes('/') || nativeSessionId.includes('\\') || nativeSessionId === '.' || nativeSessionId === '..') {
    return null;
  }
  const sessionsDir = join(dshHome, 'sessions');
  if (!existsSync(sessionsDir)) return null;
  try {
    for (const slug of readdirSync(sessionsDir)) {
      const candidate = join(sessionsDir, slug, nativeSessionId);
      try {
        if (statSync(candidate).isDirectory()) {
          const entries = readdirSync(candidate);
          if (entries.some((f) => f.startsWith('session.') && (f === 'session.v4.jsonl' || f === 'session.v4.jsonl.zstd'))) {
            return candidate;
          }
        }
      } catch {
        // ignore unreadable entries
      }
    }
  } catch {
    return null;
  }
  return null;
}

export class DeepSeekAdapter implements AgentAdapter {
  private _emitter = new EventEmitter();
  private _rpc: DeepSeekRpc | null = null;
  private _readyPromise: Promise<void> | null = null;
  private _readyError: Error | null = null;
  private _sessionId = '';
  private _dshSessionId = '';
  private _seq = 0;
  private _model = '';
  private _contextWindowSize: number | undefined = undefined;
  private _cwd = '';
  private _endResolve: (() => void) | null = null;
  /** Set when turn/end arrives before sendPrompt registers _endResolve. */
  private _turnEnded = false;
  private _turnErrored = false;
  private _turnUsage: UsagePartial = {};
  private _sawTextDelta = false;
  private _getNextSteer?: SessionConfig['getNextSteer'];
  private _steerLoopRunning = false;
  /** Effort passed to start(); used as fallback when sendPrompt options omit reasoningEffort. */
  private _sessionEffort: string | undefined = undefined;
  /** reasoningEffort the live RPC was initialized with. */
  private _initializedEffort: string | undefined = undefined;
  /** Whether the current _rpc needs a `session/resume` before its first `session/prompt`. */
  private _needsResume = false;
  /** True after at least one turn has been sent on `_dshSessionId` (so a respawn knows to resume). */
  private _hasPrompted = false;
  private _helpers = new Map<string, { startedAt: number }>();
  private _mcpServers: ResolvedMcpServer[] = [];
  private _mcpPatchPath: string | null = null;
  private _dshHome: string;
  readonly _spawn: SpawnFn;

  constructor(private opts: { spawn?: SpawnFn; spawnFn?: SpawnFn; bin?: string; dshHome?: string } = {}) {
    this._dshHome = opts.dshHome ?? process.env.DSH_HOME ?? join(homedir(), '.dsh');
    const extraEnv: NodeJS.ProcessEnv = {};
    if (process.env.ZAI_API_KEY) extraEnv.ZAI_API_KEY = process.env.ZAI_API_KEY;
    const inner = opts.spawn ?? opts.spawnFn ?? spawn;
    this._spawn = (c, a, o) => inner(c, a, { ...o, stdio: ['pipe', 'pipe', 'pipe'], env: buildChildEnv(extraEnv, undefined, 'deepseek') });
    this.opts = { ...opts, spawnFn: this._spawn };
  }

  streamEvents(): EventEmitter { return this._emitter; }

  private _emit(event: Omit<NormalisedEvent, 'sessionId' | 'seq' | 'ts'>): void {
    this._emitter.emit('event', { ...event, sessionId: this._sessionId, seq: ++this._seq, ts: Date.now() } as NormalisedEvent);
  }

  private _settleTurn(): void {
    if (this._endResolve) { this._endResolve(); this._endResolve = null; }
    else this._turnEnded = true;
  }

  async start(config: SessionConfig): Promise<void> {
    this._sessionId = config.sessionId;
    this._model = config.model;
    this._cwd = config.cwd ?? '';
    this._dshSessionId = safeNativeSessionId(config.nativeSessionId) || config.sessionId;
    this._seq = 0;
    this._turnEnded = false;
    this._endResolve = null;
    this._readyError = null;
    this._turnErrored = false;
    this._turnUsage = {};
    this._sawTextDelta = false;
    this._getNextSteer = config.getNextSteer;
    this._steerLoopRunning = false;
    this._contextWindowSize = undefined;
    this._sessionEffort = config.effort;
    this._initializedEffort = undefined;
    this._needsResume = Boolean(safeNativeSessionId(config.nativeSessionId));
    this._hasPrompted = Boolean(safeNativeSessionId(config.nativeSessionId));
    this._helpers.clear();
    this._mcpServers = config.textOnly ? [] : (config.mcpServers ?? []);
    this._mcpPatchPath = null;

    this.listModels().then((models) => {
      this._contextWindowSize = adapterContextWindow('deepseek', models, this._model);
    }).catch(() => {
      this._contextWindowSize = adapterContextWindow('deepseek', [], this._model);
    });

    this._beginRpc(config.effort);
  }

  /** Spawn (or respawn) dsh RPC and initialize. Does not await ready — tests emit spawn first. */
  private _beginRpc(reasoningEffort?: string): void {
    const { provider, modelId } = toDshInit(this._model);
    const rpc = new DeepSeekRpc({ spawn: this._spawn, bin: this.opts.bin });
    this._rpc = rpc;

    rpc.on('notification', ({ method, params }: { method: string; params: Record<string, unknown> }) => {
      this._onNotification(method, params);
    });
    rpc.on('error', (err: Error) => {
      this._emit({ type: 'error', payload: { message: err.message } });
      this._emit({ type: 'status', payload: { status: 'error' } });
      this._turnErrored = true;
      this._endResolve?.();
      this._emitter.emit('end');
    });
    rpc.on('exit', (code: number | null) => {
      if (code !== 0 && code !== null && !this._turnErrored) {
        this._turnErrored = true;
        this._emit({ type: 'status', payload: { status: 'error' } });
      }
      this._settleTurn();
      this._rpc = null;
    });

    const args: string[] = [];
    const patchPath = ensurePiAiProviderPatch(this._dshHome, provider);
    if (patchPath) args.push('--patch', patchPath);

    let mcpEnv: Record<string, string> | undefined;
    if (this._mcpServers.length > 0) {
      const built = toDeepSeekMcpPatch(this._mcpServers);
      if (built.yaml) {
        const dir = join(this._dshHome, '.tierwyn-patches');
        const file = join(dir, `mcp-${this._dshSessionId}.yml`);
        try {
          mkdirSync(dir, { recursive: true });
          writeFileSync(file, built.yaml, { mode: 0o600 });
          this._mcpPatchPath = file;
          args.push('--patch', file);
          mcpEnv = built.env;
        } catch {
          // ignore unwritable dshHome
        }
      }
    }

    rpc.start({
      cwd: this._cwd || undefined,
      args: args.length ? args : undefined,
      env: mcpEnv,
    });

    this._readyPromise = rpc.ready().then(async () => {
      await rpc.request('initialize', {
        cwd: this._cwd,
        provider,
        model: modelId,
        reasoningEffort, // undefined is omitted by JSON.stringify
        // maxTokens: intentionally omitted — let dsh use its own default.
      });
      this._initializedEffort = reasoningEffort;
    }).catch((err: Error) => {
      this._readyError = err;
      if (this._turnErrored) return; // spawn-level failure: the rpc 'error' handler already ended the stream
      // dsh answers a failed initialize with a JSON-RPC error but keeps running —
      // kill it and end the stream so the node reclaims the session slot instead of
      // leaking it until an explicit stop (mirrors the rpc 'error' path above).
      this._turnErrored = true;
      rpc.kill();
      this._emit({ type: 'error', payload: { message: err.message } });
      this._emit({ type: 'status', payload: { status: 'error' } });
      this._endResolve?.();
      this._emitter.emit('end');
    });
  }

  private _harvestUsage(event: Record<string, unknown>): void {
    const data = sessionEventData(event);
    if (event.type === 'assistant/message') {
      Object.assign(this._turnUsage, usageFromEvent(data.usage as Record<string, unknown> | undefined));
    }
    if (event.type === 'assistant/chunk') {
      const chunk = (data.chunk && typeof data.chunk === 'object')
        ? data.chunk as Record<string, unknown>
        : {};
      if (chunk.type === 'text-delta') this._sawTextDelta = true;
      if (chunk.type === 'usage') {
        const u = (chunk.usage && typeof chunk.usage === 'object')
          ? chunk.usage as Record<string, unknown>
          : chunk;
        Object.assign(this._turnUsage, usageFromEvent(u));
      }
    }
  }

  private _onNotification(method: string, params: Record<string, unknown>): void {
    if (envPref('DSH_DEBUG')) {
      console.error(`[dsh-debug] ${method} ${JSON.stringify(params).slice(0, 4000)}`);
    }
    if (method === 'session.event') {
      const sessionId = params.sessionId as string | undefined;
      if (sessionId && sessionId !== this._dshSessionId) return;
      const event = (params.event ?? {}) as Record<string, unknown>;
      this._harvestUsage(event);
      for (const partial of mapDeepSeekEvent(event, { streamedText: this._sawTextDelta })) {
        if (partial.type === 'error') {
          if (!this._turnErrored) {
            this._emit({ type: 'status', payload: { status: 'error' } });
          }
          this._turnErrored = true;
        } else if (
          partial.type === 'status' &&
          (partial.payload as { status?: string }).status === 'error'
        ) {
          if (this._turnErrored) continue;
          this._turnErrored = true;
        }
        this._emit(partial);
      }
      // Each step terminates with assistant/message; the next step's text
      // stream starts fresh, so a step that replies without deltas still
      // gets its content emitted from the message itself.
      if (event.type === 'assistant/message') this._sawTextDelta = false;
      if (event.type === 'turn/end') this._settleTurn();
      return;
    }
    if (method === 'session.status') {
      const sessionId = params.sessionId as string | undefined;
      if (sessionId && sessionId !== this._dshSessionId) return;
      // 'running' is already emitted by turn/start; do not double-emit.
      if (params.status === 'idle') this._settleTurn();
      return;
    }
    if (method === 'subagent.started') {
      const parentSessionId = params.parentSessionId as string | undefined;
      if (parentSessionId && parentSessionId !== this._dshSessionId) return;
      const taskId = typeof params.childSessionId === 'string' ? params.childSessionId : '';
      if (!taskId) return;
      const startedAt = Date.now();
      this._helpers.set(taskId, { startedAt });
      this._emit({
        type: 'helper',
        payload: {
          taskId,
          label: 'subagent',
          description: '',
          status: 'running',
          startedAt,
        },
      });
      return;
    }
    if (method === 'subagent.finished') {
      const parentSessionId = params.parentSessionId as string | undefined;
      if (parentSessionId && parentSessionId !== this._dshSessionId) return;
      const taskId = typeof params.childSessionId === 'string'
        ? params.childSessionId
        : (typeof params.agentId === 'string' ? params.agentId : '');
      if (!taskId) return;
      const existing = this._helpers.get(taskId);
      const startedAt = existing?.startedAt ?? Date.now();
      this._helpers.delete(taskId);
      const rawStatus = params.status;
      const stopReason = typeof params.stopReason === 'string' ? params.stopReason.toLowerCase() : '';
      let status: Exclude<HelperStatus, 'running'> = 'failed';
      if (rawStatus === 'ok') status = 'completed';
      else if (stopReason === 'cancelled' || stopReason === 'aborted' || stopReason === 'stopped') status = 'stopped';
      const provider = typeof params.provider === 'string' && params.provider.trim() ? params.provider.trim() : 'subagent';
      const summary = extractAssistantSummary(params.lastAssistantMessage);
      this._emit({
        type: 'helper',
        payload: {
          taskId,
          label: provider,
          description: '',
          status,
          startedAt,
          ...(summary ? { summary } : {}),
        },
      });
    }
  }

  async sendPrompt(text: string, attachments: Attachment[] = [], _model?: string, _effort?: EffortLevel, options?: PromptOptions): Promise<void> {
    if (!this._rpc) throw new Error('DeepSeekAdapter.sendPrompt called before start()');
    if (this._readyPromise) { await this._readyPromise; this._readyPromise = null; }
    if (this._readyError) throw this._readyError;

    const effort = resolveDeepSeekReasoningEffort(options, this._sessionEffort);
    if (effort !== this._initializedEffort) {
      const old = this._rpc;
      old.removeAllListeners();
      old.kill();
      this._rpc = null;
      this._readyError = null;
      if (this._hasPrompted) this._needsResume = true;
      this._beginRpc(effort);
      if (this._readyPromise) { await this._readyPromise; this._readyPromise = null; }
      if (this._readyError) throw this._readyError;
    }

    await this._runTurn(text, attachments);
    // Hold the subprocess open for follow-up prompts on the same sessionId.
    // Emitting 'end' here would tear down the SessionRecord and the next
    // operator message would spawn a new dsh that collides with the persisted log.
    if (this._getNextSteer && this._rpc) {
      void this._runSteerLoop().catch(() => { /* loop exit is benign */ });
      return;
    }
    this._emitter.emit('end');
  }

  private async _runTurn(text: string, attachments: Attachment[] = []): Promise<void> {
    const rpc = this._rpc;
    if (!rpc) throw new Error('DeepSeekAdapter.sendPrompt called before start()');
    if (this._readyPromise) { await this._readyPromise; this._readyPromise = null; }
    if (this._readyError) throw this._readyError;

    this._turnErrored = false;
    this._turnUsage = {};
    this._sawTextDelta = false;
    this._turnEnded = false;

    const contentBlocks = [
      { type: 'text', text },
      ...attachments.filter((a) => a.base64).map((a) => ({ type: 'image', data: a.base64, mimeType: a.mediaType })),
    ];

    let endPromise: Promise<void> = Promise.resolve();
    try {
      if (this._needsResume) {
        this._needsResume = false;
        // Restore the persisted session on the new dsh process so session/prompt
        // does not collide with the existing `.dsh/sessions` log on disk.
        // Best-effort: older dsh (0.1.x) without session/resume or a not-yet-flushed
        // session ignores the error and falls through to session/prompt.
        await rpc.request('session/resume', { sessionId: this._dshSessionId }).catch(() => {});
        // Ignore anything replayed during resume; arm the turn latch only now.
        this._turnEnded = false;
        this._sawTextDelta = false;
      }
      endPromise = new Promise<void>((resolve) => {
        this._endResolve = resolve;
        if (this._turnEnded) resolve();
      });
      this._hasPrompted = true;
      await rpc.request('session/prompt', { sessionId: this._dshSessionId, contentBlocks });
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      this._emit({ type: 'error', payload: { message: msg } });
      this._emit({ type: 'status', payload: { status: 'error' } });
      this._turnErrored = true;
      this._settleTurn();
    }
    await endPromise;

    if (!this._turnErrored) {
      const occ = contextWindowOccupancy({
        inputTokens: this._turnUsage.inputTokens,
        cacheReadTokens: this._turnUsage.cacheReadTokens,
      });
      const contextWindowPct = computeContextWindowPct(occ, this._contextWindowSize);
      this._emit({ type: 'status', payload: { status: 'done', ...this._turnUsage, contextWindowPct } });
    }
  }

  getLiveContextWindowUsage(): { contextWindowPct?: number; contextWindowSize?: number } {
    const occ = contextWindowOccupancy({
      inputTokens: this._turnUsage.inputTokens,
      cacheReadTokens: this._turnUsage.cacheReadTokens,
    });
    if (!this._contextWindowSize || occ <= 0) return {};
    const contextWindowPct = computeContextWindowPct(occ, this._contextWindowSize);
    return { contextWindowPct, contextWindowSize: this._contextWindowSize };
  }

  private async _runSteerLoop(): Promise<void> {
    if (this._steerLoopRunning) return;
    this._steerLoopRunning = true;
    try {
      while (this._rpc && this._getNextSteer) {
        let next: { text: string; attachments?: Attachment[] } | null;
        try {
          next = await this._getNextSteer();
        } catch {
          break;
        }
        if (!next) break;
        if (!this._rpc) break;
        try {
          await this._runTurn(next.text, next.attachments ?? []);
        } catch {
          break;
        }
      }
    } finally {
      this._steerLoopRunning = false;
    }
    this._emitter.emit('end');
  }

  async stop(): Promise<void> {
    try {
      await Promise.race([
        this._rpc?.request('shutdown', {}) ?? Promise.resolve(),
        new Promise((r) => setTimeout(r, 2000)),   // ponytail: don't block teardown on a wedged child
      ]).catch(() => {});
      this._emit({ type: 'status', payload: { status: 'idle' } });
    } finally {
      this._endResolve?.();
      this._rpc?.kill();
      this._rpc = null;
      if (this._mcpPatchPath) {
        try { unlinkSync(this._mcpPatchPath); } catch { /* ignore */ }
        this._mcpPatchPath = null;
      }
    }
    this._emitter.emit('end');
  }

  async listModels(): Promise<ModelDescriptor[]> {
    // ponytail: seed-driven. dsh exposes no model-list command; models come from
    // agent-profiles.json. Replace with a real probe if `dsh models --json` ships.
    return readProfiles()
      .filter((p) => p.agentType === 'deepseek')
      .map((p) => ({
        name: p.model,
        label: p.label,
        provider: p.provider,
        vision: p.vision,
        steer: p.steer,
        contextWindow: p.contextWindow,
      }));
  }

  async listCommands(): Promise<CommandDescriptor[]> {
    const dirs = [
      join(this._dshHome, 'skills'),
      join(homedir(), '.agents', 'skills'),
    ];
    if (this._cwd) {
      dirs.unshift(
        join(this._cwd, '.dsh', 'skills'),
        join(this._cwd, '.agents', 'skills'),
      );
    }
    return scanSkillDirs(dirs);
  }

  async runCommand(name: string, args?: string, options?: PromptOptions): Promise<void> {
    const slashText = `/${name}${args ? ` ${args}` : ''}`;
    await this.sendPrompt(slashText, [], undefined, undefined, options);
  }

  async listSessions(): Promise<{ id: string; summary: string; createdAt?: number }[]> {
    return []; // ponytail: dsh exposes no session/list RPC.
  }

  async loadSession(id: string): Promise<void> {
    this._dshSessionId = id;
    this._needsResume = true;
  }

  /**
   * True when either this adapter's `dsh --profile sdk` process is still up OR
   * a persisted `.dsh/sessions/<slug>/<nativeSessionId>` directory exists on disk
   * (restorable via `session/resume` in dsh 0.2.x+).
   */
  async isNativeSessionAvailable(nativeSessionId: string): Promise<boolean> {
    if (this._rpc !== null) return true;
    return locateDshSessionDir(this._dshHome, nativeSessionId) !== null;
  }

  async deleteNativeSession(nativeSessionId: string): Promise<void> {
    const located = locateDshSessionDir(this._dshHome, nativeSessionId);
    if (!located) return;
    try {
      await fsp.rm(located, { recursive: true, force: true });
    } catch (err) {
      if ((err as NodeJS.ErrnoException)?.code !== 'ENOENT') throw err;
    }
  }

  get nativeSessionId(): string { return this._dshSessionId; }
}
